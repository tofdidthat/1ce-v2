-- Run only against the independent 1CE v2 PostgreSQL database.
CREATE TABLE IF NOT EXISTS account_users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 google_id TEXT UNIQUE, email TEXT NOT NULL, password_hash TEXT,
 email_verified BOOLEAN NOT NULL DEFAULT FALSE,
 name TEXT, picture TEXT, custom_picture TEXT,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS account_users_email_lower_unique_idx ON account_users(lower(email));
CREATE TABLE IF NOT EXISTS account_sessions (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES account_users(id) ON DELETE CASCADE,
 token_hash TEXT UNIQUE NOT NULL, created_at TIMESTAMPTZ DEFAULT now(),
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS account_sessions_user_id_idx ON account_sessions(user_id);
CREATE INDEX IF NOT EXISTS account_sessions_expires_at_idx ON account_sessions(expires_at);
